#!/usr/bin/env python3
"""Write STM32-derived 10 Hz camera trigger timestamps for version5.

The STM32 firmware emits a synthetic GPRMC sentence once per PPS second. The
10 Hz camera trigger is generated by a timer phase-locked to the same PPS
timer, so this bridge expands each validated PPS/GPRMC second into ten camera
trigger timestamps and writes them to the shared seqlock file consumed by the
UVC camera driver.
"""

import argparse
import calendar
import glob
import mmap
import os
import re
import struct
import sys
import time
from datetime import datetime

import serial


GPRMC_RE = re.compile(
    rb"\$GPRMC,(\d{6})(?:\.(\d+))?,[AV],[^,]*,[NS],[^,]*,[EW],[^,]*,[^,]*,(\d{6}),"
)


class SeqlockWriter:
    def __init__(self, path):
        self.path = os.path.expanduser(path)
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        self.fd = os.open(self.path, os.O_RDWR | os.O_CREAT | os.O_TRUNC, 0o666)
        os.ftruncate(self.fd, 16)
        self.mm = mmap.mmap(self.fd, 16, mmap.MAP_SHARED, mmap.PROT_WRITE | mmap.PROT_READ)
        self.seq = 0

    def write(self, timestamp_ns):
        self.seq += 2
        struct.pack_into("q", self.mm, 0, self.seq - 1)
        struct.pack_into("q", self.mm, 8, int(timestamp_ns))
        struct.pack_into("q", self.mm, 0, self.seq)
        self.mm.flush()

    def close(self):
        self.mm.close()
        os.close(self.fd)


def nmea_checksum_ok(line):
    if b"*" not in line:
        return False
    payload, given = line.strip().split(b"*", 1)
    if not payload.startswith(b"$"):
        return False
    checksum = 0
    for ch in payload[1:]:
        checksum ^= ch
    try:
        return checksum == int(given[:2], 16)
    except ValueError:
        return False


def parse_gprmc_epoch_ns(line):
    if not nmea_checksum_ok(line):
        return None
    match = GPRMC_RE.search(line)
    if not match:
        return None
    hhmmss, frac, ddmmyy = match.groups()
    hh = int(hhmmss[0:2])
    mm = int(hhmmss[2:4])
    ss = int(hhmmss[4:6])
    day = int(ddmmyy[0:2])
    month = int(ddmmyy[2:4])
    year = 2000 + int(ddmmyy[4:6])
    frac_ns = 0
    if frac:
        frac_ns = int((frac + b"0" * 9)[:9])
    dt = datetime(year, month, day, hh, mm, ss)
    return calendar.timegm(dt.timetuple()) * 1_000_000_000 + frac_ns


def auto_serial_port():
    candidates = []
    candidates.extend(glob.glob("/dev/serial/by-id/*"))
    candidates.extend(glob.glob("/dev/ttyUSB*"))
    candidates.extend(glob.glob("/dev/ttyACM*"))
    return sorted(candidates)[0] if candidates else None


def main():
    parser = argparse.ArgumentParser(
        description="Expand STM32 GPRMC/PPS seconds into 10 Hz trigger timestamps."
    )
    parser.add_argument("--port", default=os.environ.get("STM32_SERIAL_PORT", "auto"))
    parser.add_argument("--baud", type=int, default=9600)
    parser.add_argument("--output", default="/home/nuc/stm32_trigger_time")
    parser.add_argument("--period-us", type=int, default=100000)
    parser.add_argument(
        "--phase-us",
        type=int,
        default=0,
        help="Camera trigger phase after the GPRMC/PPS second edge.",
    )
    parser.add_argument("--ready-file", default="/tmp/stm32_trigger_bridge.ready")
    parser.add_argument("--log-every", type=int, default=10)
    args = parser.parse_args()

    port = auto_serial_port() if args.port == "auto" else args.port
    if not port:
        print("ERROR: no STM32 serial port found under /dev/serial/by-id, /dev/ttyUSB*, or /dev/ttyACM*", file=sys.stderr)
        return 2

    writer = SeqlockWriter(args.output)
    period_ns = args.period_us * 1000
    phase_ns = args.phase_us * 1000
    print(
        f"STM32 trigger bridge: port={port} baud={args.baud} output={args.output} "
        f"period_us={args.period_us} phase_us={args.phase_us}",
        flush=True,
    )

    serial_dev = serial.Serial(port, args.baud, timeout=0.2)
    frame_count = 0
    pps_count = 0
    last_pps_ns = None
    try:
        while True:
            line = serial_dev.readline()
            pps_ns = parse_gprmc_epoch_ns(line)
            if pps_ns is None:
                continue
            if last_pps_ns is not None and pps_ns <= last_pps_ns:
                print(f"WARN: non-monotonic GPRMC second ignored: {pps_ns} <= {last_pps_ns}", flush=True)
                continue
            if last_pps_ns is not None and abs((pps_ns - last_pps_ns) - 1_000_000_000) > 2_000_000:
                print(
                    f"WARN: GPRMC second jump: delta_ns={pps_ns - last_pps_ns}",
                    flush=True,
                )
            last_pps_ns = pps_ns
            pps_count += 1
            for k in range(10):
                trigger_ns = pps_ns + phase_ns + k * period_ns
                writer.write(trigger_ns)
                frame_count += 1
                if frame_count == 1:
                    with open(args.ready_file, "w", encoding="ascii") as ready:
                        ready.write(str(trigger_ns) + "\n")
                if frame_count <= 20 or frame_count % args.log_every == 0:
                    print(
                        f"trigger frame={frame_count} pps={pps_ns} k={k} trigger_ns={trigger_ns}",
                        flush=True,
                    )
                time.sleep(args.period_us / 1_000_000.0)
    finally:
        writer.close()


if __name__ == "__main__":
    raise SystemExit(main())
